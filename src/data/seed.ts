export function quoteTotals(items: QuoteItem[], discount = 0, taxRate = 0) {
  const labor = items.reduce((s, i) => s + i.hours * i.hourlyCost * i.qty, 0);
  const extras = items.reduce(
    (s, i) => s + (i.toolsCost + i.productionCost + i.freelancerCost) * i.qty,
    0,
  );
  const cost = labor + extras;
  const hours = items.reduce((s, i) => s + i.hours * i.qty, 0);
  const sell = items.reduce((s, i) => s + i.sellPrice * i.qty, 0);
  const afterDiscount = sell - discount;
  const tax = afterDiscount * taxRate;
  const total = afterDiscount + tax;
  const profit = afterDiscount - cost;
  const margin = afterDiscount === 0 ? 0 : profit / afterDiscount;
  const breakEven = cost;
  return { labor, extras, cost, hours, sell, afterDiscount, tax, total, profit, margin, breakEven };
}
